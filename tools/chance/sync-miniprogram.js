const fs = require('node:fs')
const path = require('node:path')

const repo = path.resolve(__dirname, '../..')
const android = path.join(repo, 'app/src/main/assets/chance')
const output = path.join(repo, 'miniprogram/lib/chance-engine/original')
const games = ['dice', 'cup', 'lots', 'scratch', 'revolver', 'slot', 'wheel']
const checking = process.argv.includes('--check')
const engineGlobals = ['EonAnim', 'EonCarnival', 'EonChance', 'EonDice', 'EonDicePhysics',
  'EonGL', 'EonRevolverModel', 'EonScratchArt', 'EonScratchStage', 'EonSlotModel', 'EonStudio']

function pathsInList(code, key) {
  const declaration = code.match(new RegExp(`\\b${key}:\\s*\\[([^\\]]*)\\]`))
  return declaration ? [...declaration[1].matchAll(/'([^']+)'/g)].map((item) => item[1]) : []
}

function write(file, content) {
  const target = path.join(output, file)
  if (checking) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      console.error(`Android scene source changed: ${path.relative(repo, target)}`)
      process.exitCode = 1
    }
    return
  }
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, content)
}

function moduleSource(file) {
  const source = fs.readFileSync(path.join(android, file), 'utf8')
  const referenced = engineGlobals.filter((key) => new RegExp(`(^|[^.\\w])${key}\\b`).test(source))
  const globals = referenced.length ? `  const { ${referenced.join(', ')} } = window\n` : ''
  return `// Synced from Android chance/${file}. Run node tools/chance/sync-miniprogram.js.\n` +
    'module.exports = function mountOriginal(platform) {\n' +
    '  const { window, document, location, matchMedia, requestAnimationFrame, cancelAnimationFrame,\n' +
    '    ResizeObserver, Image, performance, devicePixelRatio, setTimeout, clearTimeout } = platform\n' +
    '  const globalThis = window\n' + globals + '\n;\n' + source + '\n}\n'
}

const entries = []
const files = new Set()
for (const game of games) {
  const scene = `scenes/${game}/scene.js`
  const source = fs.readFileSync(path.join(android, scene), 'utf8')
  const dependencies = [
    ...pathsInList(source, 'libs').map((lib) => `lib/${lib}`),
    ...pathsInList(source, 'requires').map((file) => `scenes/${game}/${file}`),
    scene,
  ]
  dependencies.forEach((file) => files.add(file))
  entries.push(`  ${game}: [${dependencies.map((file) => `require('./${file.slice(0, -3)}')`).join(', ')}],`)
}

for (const file of files) write(file, moduleSource(file))
write('index.js', '// Generated by node tools/chance/sync-miniprogram.js.\nmodule.exports = {\n' + entries.join('\n') + '\n}\n')
